"""Propose a Madgrades grade refresh for JEFF7712/uwagent.

uwagent vendors data/grades.json, historical grade distributions over the
newest fall and spring terms Madgrades publishes. Madgrades adds terms by
hand at irregular times, so this polls: `fetch-madgrades --if-new` makes one
call to the public /terms endpoint and writes nothing unless a term is newer
than the file's window. When one is, the full fetch (about 25 minutes) runs,
the build and the grade tests must pass, and the refreshed file goes up as a
`chore/grades-<term>` PR that a person merges; uwagent's own release path
deploys it.

Dependencies install offline from the release's pinned npm cache, under the
flake's build of the same node release. The application's npm scripts see
only PATH, HOME, the npm cache and the Madgrades token, never the CI tokens.
"""

from __future__ import annotations

import json
import os
import subprocess
import tarfile
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

from scripts.ci.nixos_deploy import Checkout, Forgejo
from scripts.ci.node_supply import (
    FORGEJO_HOST,
    OWNER,
    digest,
    download,
    nix_toolchain,
    toolchain_version,
)

ROOT = Path(__file__).resolve().parents[2]
APPLICATION = "uwagent"
REPOSITORY = "JEFF7712/uwagent"
MAIN = "main"
GRADES = "data/grades.json"
BRANCH_PREFIX = "chore/grades-"
# The rest of the suite reads a local, git-ignored plan.json.
TESTS = ("tests/grades.test.ts", "tests/recommend.test.ts")
TOOLCHAIN = "node.tar.gz"
CACHE = "npm-cache.tar.gz"


def newest_term(grades: dict[str, Any]) -> str:
    return grades["window"][-1]


def branch(term: str) -> str:
    return BRANCH_PREFIX + term


def describe(old: str, new: str) -> tuple[str, str]:
    title = f"chore(data): refresh Madgrades grades through {new}"
    body = "\n".join(
        [
            f"Madgrades now publishes {new}; data/grades.json covered terms "
            f"through {old}.",
            "",
            "Regenerated by the homelab `uwagent-grades-refresh` operation with "
            "`npm run fetch-madgrades -- --if-new`. `npm run build` and "
            f"`vitest run {' '.join(TESTS)}` passed on the refreshed file.",
        ]
    )
    return title, body


def open_refresh(pulls: list[dict[str, Any]]) -> dict[str, Any] | None:
    """An open refresh PR, which a new run would only duplicate."""
    return next(
        (pull for pull in pulls if pull["head"]["ref"].startswith(BRANCH_PREFIX)),
        None,
    )


def supply(catalog: dict[str, Any], filename: str) -> dict[str, Any]:
    application = next(
        item for item in catalog["applications"] if item["id"] == APPLICATION
    )
    return next(
        item for item in application["release_supply"] if item["filename"] == filename
    )


def retained(item: dict[str, Any], dest: Path) -> Path:
    if not download(
        item["package"], item["version"], item["filename"], dest, FORGEJO_HOST, OWNER
    ):
        raise ValueError(f"Pinned supply is missing: {item['filename']}")
    if digest(dest) != item["sha256"]:
        raise ValueError(f"Retained {item['filename']} does not match its pin")
    return dest


class Node:
    """The flake's node with the release's npm cache, run with a bare environment."""

    def __init__(self, catalog: dict[str, Any], work: Path) -> None:
        archive = retained(supply(catalog, TOOLCHAIN), work / TOOLCHAIN)
        toolchain = nix_toolchain(work, toolchain_version(archive))
        self.bin = toolchain / "node" / "bin"
        self.npm = toolchain / "node/lib/node_modules/npm/bin/npm-cli.js"
        self.cache = work / "npm-cache"
        self.cache.mkdir()
        with tarfile.open(retained(supply(catalog, CACHE), work / CACHE)) as tar:
            tar.extractall(self.cache, filter="data")
        self.home = work / "home"
        self.home.mkdir()

    def npm_run(
        self, cwd: Path, *args: str, extra: dict[str, str] | None = None
    ) -> None:
        env = {
            "PATH": f"{self.bin}:{os.environ['PATH']}",
            "HOME": str(self.home),
            "NPM_CONFIG_CACHE": str(self.cache),
            "NPM_CONFIG_OFFLINE": "true",
            "NPM_CONFIG_UPDATE_NOTIFIER": "false",
            **(extra or {}),
        }
        command = [str(self.bin / "node"), str(self.npm), *args]
        print("+ npm", " ".join(args), flush=True)
        subprocess.run(command, cwd=cwd, env=env, check=True)


def refresh(
    checkout: Any,
    node: Any,
    forgejo: Any,
    madgrades_token: str,
) -> str:
    """Run one poll in a uwagent checkout; returns what happened."""
    source = checkout.path
    before = newest_term(json.loads((source / GRADES).read_text()))
    node.npm_run(source, "ci", "--no-audit", "--no-fund")
    node.npm_run(
        source,
        "run",
        "fetch-madgrades",
        "--",
        "--if-new",
        extra={"MADGRADES_TOKEN": madgrades_token},
    )
    if checkout.git("diff", "--quiet", "--", GRADES, check=False).returncode == 0:
        return f"grades.json unchanged at {before}"
    after = newest_term(json.loads((source / GRADES).read_text()))
    name = branch(after)
    if forgejo.branch(name) is not None:
        return f"{name} already exists; not proposing it again"
    node.npm_run(source, "run", "build")
    node.npm_run(source, "exec", "--", "vitest", "run", *TESTS)
    title, body = describe(before, after)
    checkout.git("commit", "-m", title, "--", GRADES)
    checkout.git("push", "origin", f"HEAD:refs/heads/{name}")
    pull = forgejo.call(
        "POST", "/pulls", {"base": MAIN, "head": name, "title": title, "body": body}
    )
    return f"opened {pull['html_url']}"


def main(
    root: Path = ROOT,
    clone: Callable[..., Any] = Checkout,
    toolchain: Callable[..., Any] = Node,
) -> int:
    token = os.environ["FORGEJO_PUBLISH_TOKEN"]
    madgrades_token = os.environ["MADGRADES_TOKEN"]
    forgejo = Forgejo(token, REPOSITORY)
    pending = open_refresh(forgejo.call("GET", "/pulls?state=open&limit=50"))
    if pending is not None:
        print(f"refresh PR {pending['html_url']} is still open; not polling")
        return 0
    catalog = json.loads((root / "config/ci/applications.json").read_text())
    with tempfile.TemporaryDirectory(prefix="uwagent-grades-") as directory:
        work = Path(directory)
        checkout = clone(token, work, REPOSITORY)
        node = toolchain(catalog, work)
        print(refresh(checkout, node, forgejo, madgrades_token))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
